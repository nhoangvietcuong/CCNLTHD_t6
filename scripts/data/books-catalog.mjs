/** @param {string} text */
export function slugify(text) {
  return text.normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[đĐ]/g, 'd').toLowerCase()
    .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}
/** @param {string} name @param {string} author */
export function bookIdentity(name, author) { return `${slugify(name)}::${slugify(author)}`; }

